"""Write the SI section on the multimode line shape (paper/si_fcwd.tex).

Runs fcwd_multimode.analyse for BDP and I2-BDP at three outer-sphere
reorganization energies and tabulates lambda, Huang-Rhys factors, the
leading modes and the S1->T1 rate against the single-mode MLJ value.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from fcwd_multimode import ROOT, analyse  # noqa: E402

NAMES = ["BDP", "I2-BDP"]
SOLV = [0.0, 0.05, 0.10]


def sci(x):
    m, e = f"{x:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def main():
    res = {(n, l): analyse(n, l) for n in NAMES for l in SOLV}
    L = [r"\section{Multimode line shape for BDP and I2-BDP}", r"\label{sec:si-fcwd}", ""]
    L.append(
        r"The B3LYP/def2-SVP S$_0$ Hessian is diagonalized after projecting out translations and rotations. "
        r"The $\Delta$SCF S$_1$ and T$_1$ minima are aligned on the S$_0$ minimum (mass-weighted Kabsch) and their "
        r"displacements projected on the S$_0$ normal modes give Huang--Rhys factors $S_j=\omega_j\Delta Q_j^2/2$ "
        r"(displaced harmonic oscillators, no Duschinsky rotation, S$_0$ frequencies for all states). Modes below "
        r"200~cm$^{-1}$ are treated classically and added to an optional outer-sphere $\lambda_\mathrm{out}$; the "
        r"density of states is the Kubo generating-function line shape at 298~K with a minimum Gaussian width "
        r"of 0.01~eV. The S$_1\leftrightarrow$T$_1$ Huang--Rhys factors use the difference of the two displacements. "
        r"The gap and coupling are the pipeline values; MLJ is the single-mode model of the main text "
        r"($\lambda_s=0.10$~eV, $\hbar\omega=0.17$~eV, $S=0.8$). Generated by \texttt{paper/analysis/fcwd\_table.py}."
    )
    L.append("")
    L += [r"\begin{table}[h]\centering\small",
          r"\caption{Reorganization energies from the S$_0$ normal modes (eV) and S$_1\leftrightarrow$T$_1$ line-shape "
          r"parameters. $\lambda(\mathrm{X})$: relaxation energy of state X from the S$_0$ minimum.}",
          r"\begin{tabular}{lcccccc}\hline",
          r"Dye & $\lambda(\mathrm{S}_1)$ & $\lambda(\mathrm{T}_1)$ & $\lambda_{\mathrm{S}_1\mathrm{T}_1}$ & "
          r"$\sum S_j$ ($>200$~cm$^{-1}$) & $\langle\hbar\omega\rangle$ (cm$^{-1}$) & leading modes, cm$^{-1}$ ($S_j$) \\ \hline"]
    for n in NAMES:
        r = res[(n, 0.0)]
        d = r["displacements"]
        for c in r["channels"]:
            if c["channel"] != "S1->T1":
                continue
            kind = c["model"]
            lab = n if kind == "min" else f"{n} (TDA gradients)"
            top = ", ".join(f"{m['omega_cm']:.0f} ({m['S']:.2f})" for m in c["top_modes"][:3])
            L.append(f"{lab} & {d[kind + ':S1']['lambda_from_S0_eV']:.3f} & {d[kind + ':T1']['lambda_from_S0_eV']:.3f} & "
                     f"{c['lambda_total_eV']:.3f} & {c['S_quantum']:.2f} & {c['mean_quantum_mode_cm']:.0f} & {top} \\\\")
    L += [r"\hline\end{tabular}\end{table}", ""]
    L += [r"\begin{table}[h]\centering\small",
          r"\caption{S$_1\to$T$_1$ density of states and rate with the multimode line shape against single-mode MLJ. "
          r"The BDP coupling vanishes by symmetry, so only the ratio is meaningful there. Measured "
          r"$\kisc$(I2-BDP) $=3.5\times10^{9}$~s$^{-1}$.}",
          r"\begin{tabular}{lccccc}\hline",
          r"Dye & $\lambda_\mathrm{out}$ (eV) & $\Delta E$ (eV) & $\rho_\mathrm{multi}/\rho_\mathrm{MLJ}$ & "
          r"$k_\mathrm{multi}$ (s$^{-1}$) & $k_\mathrm{MLJ}$ (s$^{-1}$) \\ \hline"]
    for n in NAMES:
        for l in SOLV:
          for c in res[(n, l)]["channels"]:
            if c["channel"] != "S1->T1":
                continue
            lab = n if c["model"] == "min" else f"{n} (grad.)"
            km = sci(c["k_multimode"]) if c["V_cm"] > 1e-2 else "--"
            kp = sci(c["k_pipeline_channel"]) if c["V_cm"] > 1e-2 else "--"
            L.append(f"{lab} & {l:.2f} & {c['dE_pipeline_eV']:.3f} & {c['ratio_multimode_to_mlj']:.2f} & {km} & {kp} \\\\")
    L += [r"\hline\end{tabular}\end{table}", ""]
    L.append(
        r"For both dyes the harmonic S$_1\leftrightarrow$T$_1$ reorganization energy is larger than the one from "
        r"energy differences at the optimized minima (0.09 and 0.12~eV, main text), which points to anharmonicity "
        r"or Duschinsky mixing along the displacement. The single-mode MLJ model of the main text assumes 0.24~eV, "
        r"above both estimates; its factor-2 agreement for I2-BDP survives because the multimode density of states at "
        r"the pipeline gap is within a factor of 1.7 of the MLJ one. "
        r"The vertical-gradient model, which describes S$_1$ by TDA rather than $\Delta$SCF, gives an "
        r"S$_1\leftrightarrow$T$_1$ reorganization energy of 0.18~eV for BDP (0.13~eV from the minima) and 0.14~eV for "
        r"I2-BDP (0.19~eV), and its density of states at the pipeline gap is 2.2--2.7 times larger for BDP and about 3 "
        r"times smaller for I2-BDP; a line shape built from vertical gradients, as for the upper triplets, is therefore "
        r"uncertain by about a factor of 3 in either direction."
    )
    open(os.path.join(ROOT, "paper", "si_fcwd.tex"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
